/** npm run sync-engine: copy packages/engine/src into supabase/functions/_shared/engine (generated). */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
for (const pkg of ['engine']) {
  const src = join(root, 'packages', pkg, 'src');
  const out = join(root, 'supabase/functions/_shared', pkg);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  for (const f of readdirSync(src)) {
    if (!f.endsWith('.ts')) continue;
    const body = readFileSync(join(src, f), 'utf8');
    writeFileSync(join(out, f), `// GENERATED by npm run sync-engine from packages/${pkg}/src/${f}. Do not edit.\n${body}`);
  }
  console.log(`synced ${pkg} → ${out}`);
}

